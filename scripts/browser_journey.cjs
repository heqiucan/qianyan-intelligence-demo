async function main() {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(12000);
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  const check = (label, value) => { assert.ok(value, label); checks.push(label); console.log('PASS ' + label); };
  const click = name => page.getByRole('button', { name, exact: true }).click();
  const nav = name => page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name, exact: true }).click();
  const status = text => page.locator('.agent-task-heading .badge').filter({ hasText: text }).waitFor();
  const visible = text => page.getByText(text, { exact: true }).first().waitFor();
  let creativeId, campaignId;
  try {
    await page.goto(base);
    assert.equal((await (await page.request.get(base + '/api/state')).json()).model.mode, 'replay');
    await page.getByRole('heading', { name: '增长工作台', exact: true }).waitFor();
    check('原紫色球体首页和八个入口保留', await page.locator('.hero-art').count() === 1 && await page.getByRole('navigation', { name: '主导航' }).getByRole('button').count() === 8);
    check('独立官网可打开', (await page.request.get(base + '/website.html')).status() === 200);
    await page.screenshot({ path: path.join(out, '01-home.png') });
    await click('从任务开始');
    check('任务起点包含四个可操作入口', await page.locator('.journey-choice').count() === 4);
    await page.locator('#task-start').screenshot({ path: path.join(out, '02-task-start.png') });
    await page.getByRole('group', { name: '本次内容场景' }).getByRole('button', { name: '医美营销' }).click();
    await page.getByRole('button', { name: /准备机构资料.*打开知识库/ }).click();
    await page.getByLabel('业务场景', { exact: true }).waitFor();
    check('医美入口直接打开对应知识页签', await page.getByLabel('业务场景', { exact: true }).inputValue() === 'medical' && await page.getByRole('button', { name: /知识库与 RAG/ }).getAttribute('aria-pressed') === 'true');
    await nav('增长工作台');
    await page.getByRole('group', { name: '本次内容场景' }).getByRole('button', { name: '直播电商', exact: true }).click();
    await page.getByRole('button', { name: /跟着示例走一遍.*查看体验路线/ }).click();
    check('体验指南解释六步并提供实际入口', await page.locator('.journey-guide-steps li').count() === 6);
    await click('从新建活动开始');
    const campaignName = '流程验收 · ' + Date.now();
    await page.getByLabel('活动名称', { exact: true }).fill(campaignName);
    await page.getByLabel('内部观察目标').fill('体验知识内容转入、模拟成交与复盘');
    await page.getByLabel('主推卖点').fill('500 ml，奶油白');
    await click('创建并开始策划');
    await page.getByRole('heading', { name: '营销与创意', exact: true }).waitFor();
    // The route changes before the post-save state refresh fills the new option.
    await page.getByLabel('选择营销活动').locator('option:checked').filter({ hasText: campaignName }).waitFor({ state: 'attached' });
    campaignId = await page.getByLabel('选择营销活动').inputValue();
    check('新活动显示下一步生成创意', (await page.locator('.journey-next').innerText()).includes('生成第一份活动创意'));
    await click('让 Agent 准备直播内容');
    await page.locator('.agent-composer').waitFor();
    await page.getByLabel('关联营销活动（可选）').locator(`option[value="${campaignId}"]:checked`).waitFor({ state: 'attached' });
    check('从创意启动的 Agent 预选同一活动', await page.getByLabel('关联营销活动（可选）').inputValue() === campaignId);
    await click('开始任务'); await status('待你审阅');
    const taskId = await page.evaluate(() => localStorage.getItem('marketing-agent-task'));
    const editor = page.getByRole('region', { name: '知识草稿编辑器' });
    check('未确认内容不能转为创意', await editor.getByRole('button', { name: '转为活动创意', exact: true }).isDisabled());
    // A long knowledge draft may be shortened for an ad. Reopening the saved transfer must still work.
    const longParagraph = '青禾随行保温杯，500 ml，奶油白。'.repeat(115);
    for (const area of await editor.locator('textarea').all()) await area.fill(longParagraph);
    await editor.getByRole('button', { name: '保存修订版本', exact: true }).click();
    await editor.getByText(/版本 2/).waitFor();
    await editor.getByRole('checkbox').check();
    await editor.getByRole('button', { name: '人工确认并保存', exact: true }).click();
    await visible('人工已确认 · 未发布');
    check('Agent 完成前仍不能转入', await editor.getByRole('button', { name: '转为活动创意', exact: true }).isDisabled());
    await click('标记任务完成'); await status('已确认完成');
    await page.reload(); await status('已确认完成');
    check('任务起点创建的 Agent 刷新后仍恢复当前任务', await page.evaluate(() => localStorage.getItem('marketing-agent-task')) === taskId && page.url().includes(taskId));
    await editor.getByRole('button', { name: '转为活动创意', exact: true }).click();
    assert.ok((await page.getByLabel('转入视频脚本').inputValue()).length > 6000, '原始长稿没有被静默截断');
    check('转入窗口保留目标活动，要求人工核对', await page.getByLabel('转入目标活动').inputValue() === campaignId && await page.getByLabel('转入目标活动').isDisabled());
    await page.getByLabel('转入创意标题').fill('青禾随行保温杯 · 规格展示');
    await page.getByLabel('转入广告正文').fill('青禾随行保温杯，500 ml，奶油白。');
    await page.getByLabel('转入视频脚本').fill('展示杯身外观、容量标识与杯盖结构。详情请查看商品资料。');
    await page.locator('dialog[open]').getByRole('checkbox').check();
    await page.route('**/api/knowledge/drafts/*/creative', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '验收模拟：转入暂未完成，请重试。' }) }));
    await click('确认转入创意草稿');
    await page.getByRole('alert').filter({ hasText: '验收模拟' }).waitFor();
    check('转入失败保留整理后的输入', await page.getByLabel('转入创意标题').inputValue() === '青禾随行保温杯 · 规格展示');
    await page.unroute('**/api/knowledge/drafts/*/creative');
    await page.locator('dialog[open]').screenshot({ path: path.join(out, '03-transfer-review.png') });
    await click('确认转入创意草稿');
    await page.getByRole('region', { name: '创意知识来源' }).waitFor();
    creativeId = await page.getByLabel('当前工作素材').inputValue();
    check('转入后打开正确活动与新素材', await page.getByLabel('选择营销活动').inputValue() === campaignId && page.url().includes(creativeId));
    const state = await (await page.request.get(base + '/api/state')).json();
    const creative = state.creatives.find(c => c.id === creativeId);
    check('来源与引用持久保存，素材仍为草稿', creative.status === 'draft' && creative.knowledge_origin.agent_task_id === taskId && creative.knowledge_origin.sources.length > 0);
    await page.getByRole('region', { name: '创意知识来源' }).screenshot({ path: path.join(out, '04-creative-origin.png') });
    await page.reload(); await page.getByRole('region', { name: '创意知识来源' }).waitFor();
    check('刷新仍定位同一活动素材与来源', await page.getByLabel('当前工作素材').inputValue() === creativeId);
    await click('查看原知识草稿');
    await page.getByRole('region', { name: '知识草稿编辑器' }).waitFor();
    check('回到原稿时定位到正确资料空间', (await page.getByLabel('机构 / 品牌资料空间').inputValue()) === 'agent-demo-live');
    await click('转为活动创意');
    await page.locator('dialog[open]').getByRole('checkbox').check();
    await click('打开已转入素材');
    await page.getByRole('region', { name: '创意知识来源' }).waitFor();
    check('重复转入只打开既有素材', await page.getByLabel('当前工作素材').inputValue() === creativeId);
    await click('核对当前文案');
    await page.getByTestId('creative-workspace').getByRole('button', { name: '确认当前素材', exact: true }).click();
    await click('确认通过素材');
    await page.getByTestId('creative-workspace').getByRole('button', { name: '用当前素材创建投放', exact: true }).click();
    await page.getByLabel('计划名称', { exact: true }).fill('Agent 来源模拟计划');
    await click('保存计划草稿');
    await page.getByRole('heading', { name: '广告投放', exact: true }).waitFor();
    await visible('计划草稿已保存，下一步确认启动');
    check('保存计划后指引实际启动操作', true);
    await click('确认启动'); await click('确认模拟启动');
    await click('体验购买');
    await click('查看商品详情');
    await page.getByRole('button', { name: /核对订单 ·/ }).click();
    await click('模拟付款并下单');
    await click('查看订单来源');
    await page.getByRole('heading', { name: '效果与获客', exact: true }).waitFor();
    check('订单返回自动切到现场数据', await page.getByLabel('数据来源', { exact: true }).inputValue() === 'session');
    check('数据来源说明解释消耗与 ROI 缺失', (await page.locator('details[aria-label="统一数据范围"]').innerText()).includes('消耗与 ROI 暂不能计算'));
    await click('查看链路');
    check('模拟订单可以追溯至转入素材', (await page.locator('dialog[open]').innerText()).includes('规格展示'));
    await click('关闭弹窗');
    await page.getByLabel('数据来源', { exact: true }).selectOption('history');
    await page.getByLabel('投放计划筛选').selectOption('');
    await click('看我刚才的购买');
    check('一键找回现场数据并清除筛选', await page.getByLabel('数据来源', { exact: true }).inputValue() === 'session' && await page.getByLabel('投放计划筛选').inputValue() === '');
    await page.getByRole('button', { name: '基于当前范围进行复盘', exact: true }).click();
    await click('生成本轮复盘');
    await visible('保存本轮结论与下一步');
    await page.getByRole('button', { name: '去保存活动报告', exact: true }).click();
    await page.getByLabel('报告标题', { exact: true }).fill('Agent 内容到测试订单的流程报告');
    await click('保存新的报告快照');
    await visible('本轮已有报告，可以继续下一次迭代');
    check('内容、素材、模拟订单、复盘与报告闭环可操作', true);
    await page.screenshot({ path: path.join(out, '05-report.png') });
    await nav('增长工作台');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('#task-start').scrollIntoViewIfNeeded();
    check('390px 入口和流程无页面横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    check('减少动画设置应用到新入口', await page.locator('.journey-choice').first().evaluate(el => getComputedStyle(el).transitionDuration === '0s'));
    await page.screenshot({ path: path.join(out, '06-mobile-start.png') });
    await page.goto(base + '/#/creative?item=' + creativeId);
    await page.getByRole('region', { name: '创意知识来源' }).waitFor();
    check('390px 创意和来源无页面横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.goto(base + '/#/overview?agent=' + taskId);
    await status('已确认完成');
    await page.getByRole('button', { name: '转为活动创意', exact: true }).click();
    check('390px 转入弹窗无横向溢出', await page.locator('dialog[open]').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    await page.screenshot({ path: path.join(out, '07-mobile-transfer.png') });
    check('没有浏览器脚本异常', errors.length === 0);
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ ok: true, checks, errors, campaignId, creativeId }, null, 2));
  } catch (e) {
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ ok: false, checks, errors, error: e.message, campaignId, creativeId }, null, 2));
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true });
    fs.writeFileSync(path.join(out, 'failure.json'), JSON.stringify({ error: e.message, checks, errors, url: page.url() }, null, 2));
    throw e;
  } finally { await browser.close(); }
}
main().catch(e => { console.error(e); process.exit(1); });
