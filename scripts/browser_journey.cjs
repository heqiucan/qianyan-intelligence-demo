/* Use only the isolated replay server started with tmp/journey-acceptance/data. */
const { chromium } = require('C:/Users/16620/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.DEMO_TEST_BASE || 'http://127.0.0.1:8031';
const out = path.resolve('tmp/journey-acceptance/browser');
