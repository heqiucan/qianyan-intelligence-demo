/* End-to-end verification against the isolated V2 service only. */
const { chromium } = require('./playwright_runtime.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.DEMO_TEST_URL || 'http://127.0.0.1:8020';
assert.equal(new URL(base).hostname, '127.0.0.1');
assert.equal(new URL(base).port, '8020', 'Do not run this against user data');
const out = path.resolve('tmp/v2-acceptance/browser'); fs.mkdirSync(out, { recursive: true });
async function main() {
 const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
 const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
 page.setDefaultTimeout(12000);
 const checks = [], errors = []; page.on('pageerror', e => errors.push(e.message));
 const check = (label, value) => { assert.ok(value, label); checks.push(label); console.log('PASS ' + label); };
 const state = async () => (await page.request.get(base + '/api/state')).json();
 const nav=async name=>{await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name,exact:true}).click();await page.getByRole('heading',{level:1,name,exact:true}).waitFor();};
 async function saved(locator, endpoint, method = 'POST') {
  const [response] = await Promise.all([page.waitForResponse(r => new URL(r.url()).pathname === '/api' + endpoint && r.request().method() === method), locator.click()]);
  const data = await response.json(); assert.equal(response.status(), 200, JSON.stringify(data));
  await page.waitForFunction(() => !document.querySelector('.busy-indicator'));
  return data;
 }
 try {
  await page.goto(base); await page.getByRole('heading', { name: '增长工作台', exact: true }).waitFor();
  const expectedBuyerType = (await state()).orders.some(o => o.buyer_id === 'new-001') ? 'returning' : 'new';
  await page.screenshot({ path: path.join(out, '01-overview.png'), fullPage: true });
  const campaignName = '浏览器验收 · 商品推广 · ' + Date.now();
  await page.getByRole('button', { name: '新建营销活动', exact: true }).click();
  await page.getByLabel('活动名称', { exact: true }).fill(campaignName);
  await page.getByLabel('内部观察目标', { exact: true }).fill('核验模拟订单与新客的联动');
  await page.getByLabel('受众假设', { exact: true }).fill('通勤场景（待验证）');
  await page.getByLabel('主推卖点', { exact: true }).fill('500 ml 奶油白');
  await page.getByLabel('预算上限', { exact: true }).fill('500');
  const campaign = await saved(page.getByRole('button', { name: '创建并开始策划', exact: true }), '/campaigns');
  check('活动策略实际保存', campaign.goal.includes('模拟订单') && campaign.budget_limit === 500);
  await nav('营销与创意');
  const generated = await saved(page.getByRole('button', { name: '生成两组创意', exact: true }), `/campaigns/${campaign.id}/generate`);
  check('生成两组独立创意', generated.length === 2);
  const card = page.locator('.creative-card').filter({ has: page.getByRole('heading', { name: generated[0].title, exact: true }) });
  await card.getByRole('button', { name: '编辑', exact: true }).click();
  const creativeTitle = '500 ml，把日常带在身边';
  await page.getByLabel('标题', { exact: true }).fill(creativeTitle);
  await page.getByLabel('海报模板', { exact: true }).selectOption('minimal');
  const creative = await saved(page.getByRole('button', { name: '保存为新版本', exact: true }), `/creatives/${generated[0].id}/revise`);
  check('编辑保留版本且模板保存', creative.version === 2 && creative.template === 'minimal');
  let updated = page.locator('.creative-card').filter({ has: page.getByRole('heading', { name: creativeTitle, exact: true }) });
  await updated.getByRole('button', { name: '版本对比', exact: true }).click();
  check('对照原版文案可见', await page.locator('dialog').getByRole('heading', { name: generated[0].title, exact: true }).isVisible());
  await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await updated.getByRole('button', { name: '预览 / 导出', exact: true }).click();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: '导出 PNG 海报', exact: true }).click();
  const file = await download; await file.saveAs(path.join(out, 'poster.png')); check('海报真实导出', fs.statSync(path.join(out, 'poster.png')).size > 1000);
  await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await updated.getByRole('button', { name: '确认素材', exact: true }).click();
  await saved(page.getByRole('button', { name: '确认通过素材', exact: true }), `/creatives/${creative.id}/approve`);
  await updated.getByRole('button', { name: '用于投放', exact: true }).click();
  await page.getByLabel('计划名称', { exact: true }).fill('通勤创意 V2 · 验收投放');
  check('投放预选正确素材版本', await page.getByLabel('已确认素材', { exact: true }).inputValue() === creative.id);
  const plan = await saved(page.getByRole('button', { name: '保存计划草稿', exact: true }), '/plans');
  let row = page.getByRole('row').filter({ hasText: plan.name });
  await row.getByRole('button', { name: '编辑草稿', exact: true }).click();
  await page.getByLabel('计划总预算', { exact: true }).fill('280');
  const edited = await saved(page.getByRole('button', { name: '保存计划草稿', exact: true }), `/plans/${plan.id}`, 'PUT');
  check('编辑草稿产生配置版本', edited.budget === 280 && edited.config_version === 2);
  await row.getByRole('button', { name: '确认启动', exact: true }).click();
  await saved(page.getByRole('button', { name: '确认模拟启动', exact: true }), `/plans/${plan.id}/status`);
  await row.getByRole('button', { name: '体验购买', exact: true }).click();
  await page.getByRole('button', { name: creative.cta, exact: true }).click();
  await page.getByLabel('购买数量', { exact: true }).fill('2');
  await page.getByRole('button', { name: /核对订单/ }).click();
  check('付款前展示确认页', await page.getByRole('heading', { name: '再核对一下，这次购买。', exact: true }).isVisible());
  const order = await saved(page.getByRole('button', { name: '模拟付款并下单', exact: true }), '/orders');
  check('数量金额和买家历史由后端正确计算', order.quantity === 2 && order.amount === 198 && order.buyer_type === expectedBuyerType);
  await page.getByRole('button', { name: '查看订单来源', exact: true }).click();
  await page.getByRole('heading', { name: '效果与获客', exact: true }).waitFor();
  await page.getByRole('button', { name: '查看链路', exact: true }).click();
  check('订单可反查素材和配置', (await page.locator('dialog').innerText()).includes(creativeTitle));
  await page.screenshot({ path: path.join(out, '02-order-trace.png'), fullPage: true });
  await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await page.reload(); await page.getByRole('heading', { name: '效果与获客', exact: true }).waitFor();
  check('刷新后活动与来源保留', await page.getByLabel('选择营销活动').inputValue() === campaign.id);
  const final = await state();
  check('新版本未覆盖原素材及其他组', final.creatives.find(c => c.id === generated[0].id).title === generated[0].title && final.creatives.find(c => c.id === generated[1].id).version === 1);
  check('只保存一笔现场订单', final.orders.filter(o => o.plan_id === plan.id).length === 1);
  await nav('活动报告');
  await page.getByLabel('报告标题', { exact: true }).fill('商品推广现场验收报告');
  await page.getByLabel('运营结论（人工判断）', { exact: true }).fill('本次模拟购买两件商品，金额198元。现场未提供广告消耗，不计算ROI。');
  const report = await saved(page.getByRole('button', { name: '保存新的报告快照', exact: true }), '/reports');
  check('报告范围和金额一致', report.snapshot.analytics.metrics.revenue === 198 && report.snapshot.analytics.metrics.spend === null);
  await page.screenshot({ path: path.join(out, '03-report.png'), fullPage: true });
  await nav('增长工作台'); await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  check('390宽页面无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: path.join(out, '04-mobile.png'), fullPage: true });
  check('浏览器无脚本错误', errors.length === 0);
  fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ passed: checks.length, checks, errors, campaignId: campaign.id, planId: plan.id }, null, 2));
 } catch (e) {
  await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true }).catch(() => {});
  fs.writeFileSync(path.join(out, 'failure.json'), JSON.stringify({ error: String(e), checks, errors, body: (await page.locator('body').innerText()).slice(-8000) }, null, 2));
  throw e;
 } finally { await browser.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
