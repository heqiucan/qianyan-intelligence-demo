/* Browser acceptance only against the isolated replay service on port 8026. */
const { chromium } = require('./playwright_runtime.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = 'http://127.0.0.1:8026';
const out = path.resolve('tmp/rag-acceptance/browser');
fs.mkdirSync(out, { recursive: true });

async function main() {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  const check = (label, value) => { assert.ok(value, label); checks.push(label); };
  const enter = async () => { await page.goto(base + '/#/product'); await page.getByRole('button', { name: /知识库与 RAG/ }).click(); };
  const search = async query => { await page.getByLabel('输入关键词或任务').fill(query); await page.getByRole('button', { name: '检索资料', exact: true }).click(); };
  const approve = async index => {
    await page.getByRole('button', { name: '查看资料与审核' }).nth(index).click();
    const dialog = page.locator('dialog[open]');
    await dialog.getByRole('checkbox').check();
    await dialog.getByRole('button', { name: '确认资料可用', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
  };
  try {
    await page.goto(base + '/');
    await page.getByRole('heading', { name: '增长工作台', exact: true }).waitFor();
    check('保留原首页和八个主导航', await page.getByRole('navigation', { name: '主导航' }).getByRole('button').count() === 8 && await page.locator('.hero').count() === 1);
    await enter();
    await page.getByRole('button', { name: '载入本场景示例' }).click();
    await page.locator('.kb-doc-card').nth(2).waitFor();
    check('医美示例需人工审核', await page.locator('.kb-doc-card').filter({ hasText: '待人工审核' }).count() === 3);
    for (let i = 0; i < 3; i++) await approve(i);
    await page.screenshot({ path: path.join(out, '01-medical-library.png'), fullPage: true });
    await page.getByRole('button', { name: '开始检索' }).click();
    await search('咨询预约流程和审核要求');
    await page.locator('.kb-hit').first().waitFor();
    check('中文检索返回医美来源', (await page.locator('.kb-hit').allTextContents()).every(t => t.includes('澄光')));
    await page.getByRole('button', { name: '查看引用原文' }).first().click();
    check('引用原文含版本与定位', (await page.locator('dialog[open]').innerText()).includes('版本 V1') && (await page.locator('dialog[open]').innerText()).includes('段落'));
    await page.getByRole('button', { name: '关闭弹窗' }).click();
    await page.screenshot({ path: path.join(out, '02-medical-search.png'), fullPage: true });
    await page.getByRole('button', { name: '整理依据草稿（回放）' }).click();
    const editor = page.getByRole('region', { name: '知识草稿编辑器' });
    await editor.waitFor();
    check('真实检索与回放来源分别标记', (await editor.innerText()).includes('本地摘录回放 · 未调用模型'));
    const content = editor.getByLabel('第 1 段内容');
    await content.fill((await content.inputValue()) + '\n（内部核对稿）');
    await editor.getByRole('button', { name: '保存修订版本' }).click();
    await editor.getByText(/版本 2/).waitFor();
    await editor.getByRole('checkbox').check();
    await editor.getByRole('button', { name: '人工确认并保存' }).click();
    await editor.getByText('人工已确认 · 未发布', { exact: true }).waitFor();
    check('编辑、版本保存、人工确认完成', true);
    const downloadEvent = page.waitForEvent('download');
    await editor.getByRole('button', { name: '导出草稿与引用' }).click();
    const download = await downloadEvent; await download.saveAs(path.join(out, 'draft.md'));
    check('导出包含来源快照', fs.readFileSync(path.join(out, 'draft.md'), 'utf8').includes('## 引用快照'));
    await page.screenshot({ path: path.join(out, '03-medical-draft.png'), fullPage: true });
    await page.reload(); await page.getByRole('button', { name: /知识库与 RAG/ }).click();
    await page.getByRole('button', { name: /已保存草稿/ }).click();
    await page.locator('.kb-draft-item').first().click();
    check('刷新后已确认草稿仍可打开', (await page.locator('.kb-draft-editor').innerText()).includes('人工已确认 · 未发布'));
    await page.getByLabel('业务场景').selectOption('live');
    await page.getByRole('button', { name: /资料库/ , exact: false }).first().click();
    await page.getByRole('button', { name: '载入本场景示例' }).click();
    await page.locator('.kb-doc-card').nth(2).waitFor();
    for (let i = 0; i < 3; i++) await approve(i);
    await page.getByRole('button', { name: '导入资料', exact: true }).click();
    await page.locator('dialog input[type=file]').setInputFiles({ name: '直播流程.md', mimeType: 'text/markdown', buffer: Buffer.from('【虚构演示】\n\n彩虹杯直播流程：先检查杯盖，再介绍杯身。') });
    await page.getByLabel('资料标题').fill('彩虹杯演示流程');
    await page.getByRole('button', { name: '保存资料，进入审核' }).click();
    await page.locator('dialog[open]').waitFor({ state: 'hidden' });
    await page.locator('.kb-doc-card').nth(3).waitFor();
    await approve(3);
    check('上传、解析预览、保存、审核可用', true);
    await page.getByRole('button', { name: '开始检索' }).click();
    await search('保温杯规格和直播讲解');
    await page.locator('.kb-hit').first().waitFor();
    check('直播空间不混入医美资料', !(await page.locator('.kb-hit-list').innerText()).includes('澄光'));
    await page.getByRole('button', { name: '整理依据草稿（回放）' }).click();
    await page.locator('.kb-draft-editor').waitFor();
    check('直播场景生成自己的草稿', (await page.getByLabel('草稿标题').inputValue()).includes('直播'));
    await page.screenshot({ path: path.join(out, '04-live-draft.png'), fullPage: true });
    await page.getByRole('button', { name: '检索与生成', exact: true }).click();
    await search('火星玄武岩温度');
    await page.getByRole('heading', { name: '暂无可用依据' }).waitFor();
    check('无依据不显示生成入口', await page.getByRole('button', { name: '整理依据草稿（回放）' }).count() === 0);
    await page.route('**/api/knowledge/search', r => r.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '浏览器验收：模拟检索暂时失败' }) }));
    await search('彩虹杯');
    await page.getByRole('alert').filter({ hasText: '模拟检索暂时失败' }).waitFor();
    check('请求失败保留输入', await page.getByLabel('输入关键词或任务').inputValue() === '彩虹杯');
    await page.unroute('**/api/knowledge/search');
    await page.getByRole('button', { name: '检索资料', exact: true }).click();
    await page.locator('.kb-hit').first().waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    check('390宽检索页无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    check('减少动画设置有效', await page.locator('.kb-tabs button').first().evaluate(el => getComputedStyle(el).transitionDuration === '0s'));
    await page.screenshot({ path: path.join(out, '05-mobile-search.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: '营销与创意', exact: true }).click();
    await page.getByRole('button', { name: /行业知识草稿/ }).click();
    await page.locator('.kb-draft-item').first().waitFor();
    check('营销与创意入口能打开同一批知识草稿', true);
    check('浏览器没有脚本异常', errors.length === 0);
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
    console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
  } catch (e) {
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true }).catch(() => {});
    fs.writeFileSync(path.join(out, 'failure.json'), JSON.stringify({ error: e.stack, checks, errors, body: (await page.locator('body').innerText()).slice(-12000) }, null, 2));
    throw e;
  } finally { await browser.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
